const generateDemoPerdas = (): RegistroPerda[] => {
  const result: RegistroPerda[] = [];
  let idCounter = 1;

  MESES_CONFIG.forEach((mConf) => {
    if (!mConf.hasReal || mConf.targetLoss <= 0) return;
    let currentMonthLoss = 0;
    const occurrencesCount = Math.floor(mConf.targetLoss / 220) + 8; // approx 20-40 records per month

    for (let i = 0; i < occurrencesCount; i++) {
      const day = Math.min(mConf.days, Math.max(1, (i * 2) % mConf.days + 1));
      const dayStr = String(day).padStart(2, '0');
      const hour = String(8 + ((i * 3) % 14)).padStart(2, '0');
      const minute = String((i * 17) % 60).padStart(2, '0');
      const second = String((i * 23) % 60).padStart(2, '0');
      const dataHora = `${mConf.mes}-${dayStr} ${hour}:${minute}:${second}`;
      const data = `${mConf.mes}-${dayStr}`;

      const sku = DEMO_SKUS[i % DEMO_SKUS.length];
      const motObj = DEMO_MOTIVOS_BASE[(i + (day % 3)) % DEMO_MOTIVOS_BASE.length];
      const colab = DEMO_COLABORADORES[(i + day) % DEMO_COLABORADORES.length];

      // Determine loss amount
      const isLast = i === occurrencesCount - 1;
      let valorR$: number;
      if (isLast) {
        valorR$ = Math.max(15.5, mConf.targetLoss - currentMonthLoss);
      } else {
        const baseVal = (mConf.targetLoss / occurrencesCount) * (0.4 + (((i * 13) % 100) / 100) * 1.2);
        valorR$ = Math.max(8.5, Number(baseVal.toFixed(2)));
        currentMonthLoss += valorR$;
      }

      const quantidade = Math.max(1, Math.round(valorR$ / sku.unitCost));
      const hlPerdido = Number((quantidade * sku.hlUnit).toFixed(4));
      const codQuebra = motObj.cod;
      const codigoMotivo = `Q-${codQuebra}`;

      result.push({
        id: `PERD-2026-${String(idCounter++).padStart(4, '0')}`,
        data,
        dataHora,
        mesRef: mConf.mes,
        mesNome: mConf.nome,
        turno: colab.turno,
        area: motObj.area,
        codProduto: sku.cod,
        descricaoProduto: sku.desc,
        produto: `${sku.cod} - ${sku.desc}`,
        quantidade,
        codQuebra,
        codigoMotivo,
        motivo: motObj.motivo,
        colaborador: colab.nome,
        funcao: colab.funcao,
        responsavel: `${colab.nome} (${colab.funcao})`,
        valorR$: Number(valorR$.toFixed(2)),
        hectoLitro: sku.hlUnit,
        hlPerdido,
        causa: motObj.causa,
        observacao: `Ocorrência registrada no ${colab.turno}. Motivo: ${motObj.motivo}`,
        createdAt: `${data}T${hour}:${minute}:${second}Z`,
      });
    }
  });

  return result.reverse(); // Most recent first
};

